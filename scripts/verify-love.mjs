import assert from "node:assert/strict";
const origin = process.env.LOVE_TEST_ORIGIN || "http://127.0.0.1:5173";
if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(origin)) throw new Error("Run integration checks against the local preview only.");
async function request(path, options = {}) {
  const response = await fetch(origin + path, { ...options, headers: { "Content-Type": "application/json", ...options.headers } });
  return { status: response.status, data: await response.json() };
}
const draft = { sender: "Prueba", recipient: "Mi amor", title: "Un recuerdo de prueba", questions: ["¿Tu recuerdo favorito?", "¿Nuestro próximo sueño?"], letter: "Una carta que se revela al terminar." };
const created = await request("/api/rooms", { method: "POST", body: JSON.stringify(draft) });
assert.equal(created.status, 201, JSON.stringify(created.data));
const { id, token, revision } = created.data;
const base = `/api/rooms/${id}`;
const auth = { Authorization: `Bearer ${token}` };
const publicRoom = await request(base);
assert.deepEqual(publicRoom.data.questions, draft.questions);
assert.equal(publicRoom.data.letter, undefined);
assert.equal(publicRoom.data.history, undefined);
assert.equal(publicRoom.data.manage_hash, undefined);
assert.equal((await request(base + "?manage=1")).status, 403);
assert.equal((await request(base, { method: "PUT", body: JSON.stringify(draft) })).status, 403);
assert.equal((await request(base + "/answers", { method: "POST", body: JSON.stringify({ id: crypto.randomUUID(), revision, answers: ["Solo una"] }) })).status, 400);
assert.equal((await request(base + "/answers", { method: "POST", body: JSON.stringify({ id: crypto.randomUUID(), revision, answers: ["", "Otra"] }) })).status, 400);
const payload = { id: crypto.randomUUID(), revision, answers: ["Nuestra primera cita.", "Conocer el mar."] };
const first = await request(base + "/answers", { method: "POST", body: JSON.stringify(payload) });
assert.equal(first.status, 201, JSON.stringify(first.data));
assert.equal(first.data.attempt, 1);
assert.equal(first.data.letter, draft.letter);
const retry = await request(base + "/answers", { method: "POST", body: JSON.stringify(payload) });
assert.equal(retry.data.attempt, 1);
const next = await request(base + "/answers", { method: "POST", body: JSON.stringify({ ...payload, id: crypto.randomUUID(), answers: ["Nuestro primer abrazo.", "Ver las estrellas."] }) });
assert.equal(next.data.attempt, 2);
const simultaneous = await Promise.all([3,4].map(() => request(base + "/answers", { method: "POST", body: JSON.stringify({ ...payload, id: crypto.randomUUID() }) })));
assert.deepEqual(simultaneous.map(r => r.data.attempt).sort(), [3,4]);
const receipt = await request(base + "/answers/" + first.data.id);
assert.equal(receipt.data.letter, draft.letter);
const history = await request(base + "?manage=1", { headers: auth });
assert.deepEqual(history.data.history.map(item => item.attempt), [4,3,2,1]);
assert.equal(history.data.history[3].answers[0].answer, payload.answers[0]);
assert.equal(history.data.history[3].answers[0].question, draft.questions[0]);
const edited = await request(base, { method: "PUT", headers: auth, body: JSON.stringify({ ...draft, questions: ["¿Una pregunta nueva?"], letter: "Una carta nueva." }) });
assert.equal(edited.status, 200);
assert.equal((await request(base + "/answers", { method: "POST", body: JSON.stringify({ ...payload, id: crypto.randomUUID() }) })).status, 409);
const preserved = await request(base + "?manage=1", { headers: auth });
assert.equal(preserved.data.history.length, 4);
assert.equal(preserved.data.history[3].answers[0].question, draft.questions[0]);
assert.equal((await request(base + "/answers/" + first.data.id)).data.letter, draft.letter);
assert.equal((await request("/api/rooms/not-a-room")).status, 404);
assert.equal((await request("/api/rooms", { method: "POST", body: "{" })).status, 400);
assert.equal((await request("/api/rooms", { method: "POST", body: JSON.stringify({ ...draft, questions: Array(31).fill("Demasiadas") }) })).status, 400);
console.log("PASS: creation, public separation, private access, validation, sequential attempts, retry, concurrency, complete history, immutable snapshots, letter recovery and edits.");
