import assert from "node:assert/strict";
import { apiPath, creatorPath, respondentPath } from "../lib/client-urls.ts";
import { isAllowedApiOrigin, preflight, withApiCors, pagesOrigin } from "../lib/api-cors.ts";
const pages = { hostname: "lordmayes-cyber.github.io", origin: pagesOrigin };
const original = { hostname: "example.test", origin: "https://example.test" };
assert.equal(creatorPath("room-1", "private-token", pages), "/preguntas-para-mi-negrita/?edit=1&room=room-1#key=private-token");
assert.equal(respondentPath("room-1", pages), "/preguntas-para-mi-negrita/?room=room-1");
assert.equal(creatorPath(undefined, undefined, pages), "/preguntas-para-mi-negrita/?edit=1");
assert.equal(creatorPath("room-1", "private-token", original), "/?room=room-1#key=private-token");
assert.equal(respondentPath("room-1", original), "/r/room-1");
assert.ok(apiPath("/api/rooms", pages).endsWith("/api/rooms"));
assert.equal(apiPath("/api/rooms", original), "/api/rooms");
const url = "https://backend.test/api/rooms";
const options = (origin, method = "POST", headers = "authorization, content-type") => new Request(url, { method: "OPTIONS", headers: { origin, "Access-Control-Request-Method": method, "Access-Control-Request-Headers": headers } });
const allowed = preflight(options(pagesOrigin));
assert.equal(allowed.status, 204);
assert.equal(allowed.headers.get("Access-Control-Allow-Origin"), pagesOrigin);
assert.equal(allowed.headers.get("Access-Control-Allow-Credentials"), null);
assert.ok(allowed.headers.get("Access-Control-Allow-Headers").includes("Authorization"));
assert.equal(preflight(options("https://untrusted.test")).status, 403);
assert.equal(preflight(options(pagesOrigin, "DELETE")).status, 403);
assert.equal(preflight(options(pagesOrigin, "POST", "x-unexpected")).status, 403);
assert.equal(isAllowedApiOrigin(pagesOrigin, url), true);
assert.equal(isAllowedApiOrigin("https://backend.test", url), true);
assert.equal(isAllowedApiOrigin("https://untrusted.test", url), false);
const actual = withApiCors(new Request(url, { headers: { Origin: pagesOrigin } }), Response.json({ ok: true }, { headers: { Vary: "Accept-Encoding", "Cache-Control": "no-store" } }));
assert.equal(actual.headers.get("Access-Control-Allow-Origin"), pagesOrigin);
assert.equal(actual.headers.get("Vary"), "Accept-Encoding, Origin");
assert.equal(actual.headers.get("Cache-Control"), "no-store");
assert.deepEqual(await actual.json(), { ok: true });
console.log("PASS: GitHub URL routing, separate private links, API routing, restricted CORS, preflight and response headers.");
