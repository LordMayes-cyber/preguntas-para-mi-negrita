import assert from "node:assert/strict";
import { proxy } from "../vercel-site/lib/proxy.ts";
import { GET, POST } from "../vercel-site/api/rooms.mjs";
import { apiPath, creatorPath, respondentPath } from "../lib/client-urls.ts";
const id = "cb4c4967-27d9-4452-bd1a-ca8e14d43722";
const origin = "https://preguntas-para-mi-negrita.vercel.app";
let captured;
const fetcher = async (url, options) => { captured = { url: String(url), options }; return Response.json({ ok: true }); };
const response = await proxy(new Request(`${origin}/api/rooms?_route=${id}&manage=1`, { headers: { Authorization: "Bearer test-private-token", Cookie: "private=cookie", Origin: origin } }), fetcher);
assert.equal(response.status, 200);
assert.ok(captured.url.endsWith(`/api/rooms/${id}?manage=1`));
assert.equal(captured.options.headers.get("Authorization"), "Bearer test-private-token");
assert.equal(captured.options.headers.get("Cookie"), null);
assert.equal(captured.options.headers.get("Origin"), null);
assert.equal(response.headers.get("Cache-Control"), "no-store");
const payload = JSON.stringify({ answers: ["Un recuerdo."] });
await proxy(new Request(`${origin}/api/rooms/${id}/answers`, { method: "POST", headers: { Origin: origin }, body: payload }), fetcher);
assert.ok(captured.url.endsWith(`/api/rooms/${id}/answers`));
assert.equal(captured.options.body, payload);
assert.equal(captured.options.method, "POST");
assert.equal((await proxy(new Request(`${origin}/api/rooms?_route=https://untrusted.test/`), fetcher)).status, 404);
assert.equal((await proxy(new Request(`${origin}/api/rooms`, { method: "DELETE" }), fetcher)).status, 405);
assert.equal((await proxy(new Request(`${origin}/api/rooms`, { method: "POST", headers: { Origin: "https://untrusted.test" }, body: "{}" }), fetcher)).status, 403);
assert.equal((await proxy(new Request(`${origin}/api/rooms`, { method: "POST", body: "x".repeat(150001) }), fetcher)).status, 413);
assert.equal((await proxy(new Request(`${origin}/api/rooms`), async () => new Response("Unexpected page"))).status, 502);
globalThis.__GITHUB_PAGES__ = true;
globalThis.__STATIC_APP_BASE__ = "/";
globalThis.__SAME_ORIGIN_API__ = true;
assert.equal(creatorPath(id, "token"), `/?edit=1&room=${id}#key=token`);
assert.equal(respondentPath(id), `/?room=${id}`);
assert.equal(apiPath("/api/rooms"), "/api/rooms");
const originalFetch = globalThis.fetch;
try {
  globalThis.fetch = fetcher;
  assert.equal((await GET(new Request(`${origin}/api/rooms/${id}`))).status, 200);
  assert.equal((await POST(new Request(`${origin}/api/rooms`, { method: "POST", body: "{}" }))).status, 200);
} finally { globalThis.fetch = originalFetch; }
console.log("PASS: root URLs, same-origin API, private authorization, preserved submissions, restricted proxy and failures.");
